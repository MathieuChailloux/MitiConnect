# ---------------------------------------------------------------------------
# Base class : parameter declaration / reading helpers shared by the algorithms
# ---------------------------------------------------------------------------
class SlidingWindowAlgorithm(qgsUtils.BaseProcessingAlgorithm):

    WINDOW_SIZE = 'WINDOW_SIZE'          # radius of the circular window (pixels)
    CLASSES_ORDER = 'CLASSES_ORDER'
    CLASS = 'CLASS'
    QUANTILE = 'QUANTILE'
    EXPONENT = 'EXPONENT'
    DIST_MODE = 'DIST_MODE'
    DIST_COEFF_MODE = 'DIST_COEFF_MODE'
    FINAL_FUNC = 'FINAL_FUNC'
    KEEP_RANK = 'KEEP_RANK'
    DEBUG_FIELDNAME = 'DEBUG'

    FINAL_FUNCS = ['None', 'Log10', 'Exp', 'Sqrt', 'Index', 'LogIndex']
    DEFAULT_QUANTILE = 1
    DEFAULT_FINAL = 0
    OUT_NODATA = core.NODATA

    NEEDS_CLASSES_ORDER = False          # checked in checkParameterValues
    DEBUG = False

    def group(self):
        return self.tr("Sliding window")

    def groupId(self):
        return 'slidingWindow'

    # ----- parameter declaration ------------------------------------------
    def addInputParam(self):
        self.addParameter(QgsProcessingParameterRasterLayer(
            self.INPUT, self.tr("Input layer")))

    def addWindowParam(self):
        self.addParameter(QgsProcessingParameterNumber(
            self.WINDOW_SIZE,
            description=self.tr('Window radius (pixels)'),
            type=QgsProcessingParameterNumber.Integer,
            defaultValue=5,
            minValue=1))

    def addClassesOrderParam(self):
        self.addParameter(QgsProcessingParameterString(
            self.CLASSES_ORDER,
            description=self.tr('Classes order (from unfavorable to very favorable)')))

    def addClassParam(self, optional):
        self.addParameter(QgsProcessingParameterNumber(
            self.CLASS,
            description=self.tr('Class'),
            type=QgsProcessingParameterNumber.Integer,
            optional=optional))

    def addQuantileParam(self):
        self.addParameter(QgsProcessingParameterNumber(
            self.QUANTILE,
            description=self.tr('Quantile (between 0 and 1)'),
            type=QgsProcessingParameterNumber.Double,
            defaultValue=self.DEFAULT_QUANTILE,
            minValue=0.0,
            maxValue=1.0))

    def addDebugParam(self):
        self.addParameter(QgsProcessingParameterBoolean(
            self.DEBUG_FIELDNAME,
            description=self.tr('Print debug messages'),
            defaultValue=False,
            optional=True))

    def addOutputParam(self):
        self.addParameter(QgsProcessingParameterRasterDestination(
            self.OUTPUT, description=self.tr('Output layer')))

    # advanced parameters
    def addExponentParam(self):
        self.addAdvancedParam(QgsProcessingParameterNumber(
            self.EXPONENT,
            description=self.tr('Patch size exponent'),
            type=QgsProcessingParameterNumber.Integer,
            defaultValue=2,
            minValue=1))

    def addDistModeParam(self):
        self.addAdvancedParam(QgsProcessingParameterEnum(
            self.DIST_MODE,
            description=self.tr('Distance mode'),
            options=[self.tr('Minimum'), self.tr('Minimum + 1'), self.tr('Median')],
            defaultValue=core.DIST_MIN))

    def addDistCoeffParam(self):
        self.addAdvancedParam(QgsProcessingParameterEnum(
            self.DIST_COEFF_MODE,
            description=self.tr('Distance weighting mode'),
            options=[self.tr('Exponential'), self.tr('Linear')],
            defaultValue=core.COEFF_EXP))

    def addFinalFuncParam(self):
        self.addAdvancedParam(QgsProcessingParameterEnum(
            self.FINAL_FUNC,
            description=self.tr('Final function'),
            options=self.FINAL_FUNCS,
            defaultValue=self.DEFAULT_FINAL))

    def addKeepRankParam(self):
        self.addAdvancedParam(QgsProcessingParameterBoolean(
            self.KEEP_RANK,
            description=self.tr('Rank classes by position in the classes order '
                                '(comparable between rasters)'),
            defaultValue=False,
            optional=True))

    # ----- validation -----------------------------------------------------
    @staticmethod
    def parseClassesOrder(text):
        items = [s.strip() for s in (text or "").split(",") if s.strip()]
        if not items:
            raise ValueError("Please specify classes order (empty list)")
        try:
            classes = [int(s) for s in items]
        except ValueError:
            raise ValueError("Classes order must be a comma-separated list of integers")
        if len(set(classes)) != len(classes):
            raise ValueError("Classes order contains duplicates")
        return classes

    def checkParameterValues(self, parameters, context):
        if self.NEEDS_CLASSES_ORDER:
            try:
                self.parseClassesOrder(
                    self.parameterAsString(parameters, self.CLASSES_ORDER, context))
            except ValueError as e:
                return False, str(e)
        return super().checkParameterValues(parameters, context)

    # ----- parameter reading ----------------------------------------------
    def readCommon(self, parameters, context, feedback):
        self.input = self.parameterAsRasterLayer(parameters, self.INPUT, context)
        if self.input is None:
            raise QgsProcessingException(self.invalidRasterError(parameters, self.INPUT))
        self.input_path = qgsUtils.pathOfLayer(self.input)
        self.output = self.parameterAsOutputLayer(parameters, self.OUTPUT, context)
        self.DEBUG = (self.parameterAsBool(parameters, self.DEBUG_FIELDNAME, context)
                      if self.DEBUG_FIELDNAME in parameters else False)

    def readRadius(self, parameters, context):
        return self.parameterAsInt(parameters, self.WINDOW_SIZE, context)

    def readOptionalInt(self, parameters, name, context):
        value = parameters.get(name)
        if value is None or value == NULL or value == "":
            return None
        return self.parameterAsInt(parameters, name, context)

    def readEnum(self, parameters, name, context):
        return self.parameterAsEnum(parameters, name, context)

    def loadRaster(self):
        """Returns (array, nodata, valid mask, sorted list of present classes)."""
        _, array, nodata = qgsUtils.getRasterValsArrayND(str(self.input_path))
        valid = core.valid_mask(array, nodata)
        present = np.unique(array[valid]).tolist()
        return array, nodata, valid, present

    def prepareClasses(self, present, ordered, feedback):
        """Classes of `ordered` present in the raster (order kept)."""
        for c in present:
            if c not in ordered:
                feedback.pushWarning("Class " + str(c) + " order not specified")
        classes = [c for c in ordered if c in present]
        if not classes:
            raise QgsProcessingException(
                "None of the classes in the classes order is present in the raster")
        self.pushDebug(feedback, "classes = " + str(classes))
        return classes

    # ----- output / debug -------------------------------------------------
    def exportResult(self, arr, nodata, type=gdal.GDT_Float32):
        qgsUtils.exportRaster(arr, self.input_path, self.output,
                              nodata=nodata, type=type)
        return {self.OUTPUT: self.output}

    def pushDebug(self, feedback, msg):
        if self.DEBUG:
            feedback.pushDebugInfo(msg)

    def debugRaster(self, feedback, arr, outName, nodata=-9999, type=gdal.GDT_Float32):
        if self.DEBUG:
            outPath = QgsProcessingUtils.generateTempFilename(outName + ".tif")
            feedback.pushDebugInfo(outName + " path = " + str(outPath))
            qgsUtils.exportRaster(arr, self.input_path, outPath,
                                  nodata=nodata, type=type)

    def reportBackend(self, feedback):
        feedback.pushInfo("Computation backend : " + str(core.last_backend)
                          + (" (install numba for faster processing)"
                             if core.last_backend == "scipy" else ""))


