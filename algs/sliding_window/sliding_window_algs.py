# Connectivity index based on favorability
# ---------------------------------------------------------------------------
class ConnectivityIndex(SlidingWindowAlgorithm):

    ALG_NAME = 'connexityIndex'         # (sic) id kept for compatibility
    NEEDS_CLASSES_ORDER = True

    def displayName(self):
        return self.tr("Connectivity index")

    def shortHelpString(self):
        return self.tr("Connectivity index based on favorability.")

    def initAlgorithm(self, config=None):
        self.addInputParam()
        self.addWindowParam()
        self.addClassesOrderParam()
        self.addDebugParam()
        self.addOutputParam()
        self.addDistCoeffParam()
        self.addFinalFuncParam()
        self.addKeepRankParam()

    def processAlgorithm(self, parameters, context, feedback):
        self.readCommon(parameters, context, feedback)
        radius = self.readRadius(parameters, context)
        ordered = self.parseClassesOrder(
            self.parameterAsString(parameters, self.CLASSES_ORDER, context))
        coeff_mode = self.readEnum(parameters, self.DIST_COEFF_MODE, context)
        final_mode = self.readEnum(parameters, self.FINAL_FUNC, context)
        keep_rank = self.parameterAsBool(parameters, self.KEEP_RANK, context)
        array, _, valid, present = self.loadRaster()
        classes = self.prepareClasses(present, ordered, feedback)
        if keep_rank:
            ranks = [ordered.index(c) for c in classes]
            max_rank = len(ordered) - 1
        else:
            ranks = list(range(len(classes)))
            max_rank = len(classes) - 1
        self.pushDebug(feedback, "ranks = " + str(dict(zip(classes, ranks))))
        res = core.connectivity_index(array, classes, ranks, radius, coeff_mode)
        vmin, vmax = core.connectivity_bounds(radius, coeff_mode, max_rank)
        res = core.finalize(res, valid, final_mode, vmin=vmin, vmax=vmax)
        return self.exportResult(res, nodata=self.OUT_NODATA)


# ---------------------------------------------------------------------------
# Isolation index (Hanski incidence function model)
# ---------------------------------------------------------------------------
class ConnectivityIndexHabPatch(SlidingWindowAlgorithm):

    ALG_NAME = 'connectivityIndexHabPatch'

    def displayName(self):
        return self.tr("Isolation index")

    def shortHelpString(self):
        return self.tr("Isolation index inspired from Hanski incidence function model.")

    def initAlgorithm(self, config=None):
        self.addInputParam()
        self.addWindowParam()
        self.addClassParam(optional=False)
        self.addDebugParam()
        self.addOutputParam()
        self.addExponentParam()
        self.addDistModeParam()
        self.addDistCoeffParam()
        self.addFinalFuncParam()

    def processAlgorithm(self, parameters, context, feedback):
        self.readCommon(parameters, context, feedback)
        radius = self.readRadius(parameters, context)
        class_id = self.parameterAsInt(parameters, self.CLASS, context)
        exponent = self.parameterAsInt(parameters, self.EXPONENT, context)
        dist_mode = self.readEnum(parameters, self.DIST_MODE, context)
        coeff_mode = self.readEnum(parameters, self.DIST_COEFF_MODE, context)
        final_mode = self.readEnum(parameters, self.FINAL_FUNC, context)
        array, _, valid, _ = self.loadRaster()
        labels = core.label_mask((array == class_id) & valid)
        self.debugRaster(feedback, labels, "labeled", nodata=0)
        self.pushDebug(feedback, "nb patches = " + str(int(labels.max())))
        res = core.isolation_index(labels, radius, exponent, dist_mode, coeff_mode)
        self.reportBackend(feedback)
        vmin, vmax = core.isolation_bounds(radius, exponent, dist_mode, coeff_mode)
        # pixels without any patch inside the window are output as nodata
        res = core.finalize(res, valid & (res > 0), final_mode, vmin=vmin, vmax=vmax)
        return self.exportResult(res, nodata=self.OUT_NODATA)
