class NeighboursCount(SlidingWindowAlgorithm):

    ALG_NAME = 'neigboursCount'     # (sic) id kept for compatibility with saved models

    def displayName(self):
        return self.tr("Neighbours count")

    def shortHelpString(self):
        return self.tr("Computes for each pixel the number of immediate neighbours "
                       "of same value")

    def initAlgorithm(self, config=None):
        self.addInputParam()
        self.addOutputParam()

    def processAlgorithm(self, parameters, context, feedback):
        self.readCommon(parameters, context, feedback)
        array, _, valid, _ = self.loadRaster()
        counts = core.neighbours_count_4(array).astype(np.float32)
        counts[~valid] = self.OUT_NODATA
        return self.exportResult(counts, nodata=self.OUT_NODATA)


