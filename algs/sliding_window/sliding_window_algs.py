# Surface index : patch size inside the window, redistributed by class
# ---------------------------------------------------------------------------
class PatchSizeWindowRedistrib(SlidingWindowAlgorithm):

    ALG_NAME = 'patchSizeWindowRedistrib'
    NEEDS_CLASSES_ORDER = True

    def displayName(self):
        return self.tr("Surface index")

    def shortHelpString(self):
        return self.tr("Redistributed patch size inside sliding window")

    def initAlgorithm(self, config=None):
        self.addInputParam()
        self.addWindowParam()
        self.addClassesOrderParam()
        self.addQuantileParam()
        self.addDebugParam()
        self.addOutputParam()
        self.addFinalFuncParam()

    def processAlgorithm(self, parameters, context, feedback):
        self.readCommon(parameters, context, feedback)
        radius = self.readRadius(parameters, context)
        quantile = self.parameterAsDouble(parameters, self.QUANTILE, context)
        ordered = self.parseClassesOrder(
            self.parameterAsString(parameters, self.CLASSES_ORDER, context))
        final_mode = self.readEnum(parameters, self.FINAL_FUNC, context)
        array, _, valid, present = self.loadRaster()
        classes = self.prepareClasses(present, ordered, feedback)
        # Patch size inside the window (in memory, no intermediate raster)
        labels = core.label_patches(array, valid)
        size_arr = core.patch_area_window(labels, radius).astype(np.float32)
        self.debugRaster(feedback, size_arr, "prepared", nodata=0)
        res = core.redistribute_by_class(size_arr, array, classes, quantile)
        res = core.finalize(res, valid, final_mode)
        self.reportBackend(feedback)
        return self.exportResult(res, nodata=self.OUT_NODATA)


